"""Generate the Cube Kids 20-animal pack as Studio .animal.json files.

Each design is built from many small blocks (stripes, spots, manes, teeth...)
to match the voxel reference art. Stable ids ("pack-<name>") mean re-importing
updates the library entry instead of duplicating it.
Output: animal-pack/<name>.animal.json
"""
import json, os

